    /** Linear interpolation lookup. Clamps to end values when m < min or m > max (no extrapolation). */
    fun lookup(table: List<Pair<Double, Double>>, mach: Double): Double {
        if (mach <= table.first().first) return table.first().second
        if (mach >= table.last().first) return table.last().second
        var lo = 0
        var hi = table.size - 1
        while (hi - lo > 1) {
            val mid = (lo + hi) ushr 1
            if (table[mid].first <= mach) lo = mid else hi = mid
        }
        val m0 = table[lo].first
        val m1 = table[hi].first
        val c0 = table[lo].second
        val c1 = table[hi].second
        if (abs(m1 - m0) < 1e-12) return c0
        return c0 + (c1 - c0) * (mach - m0) / (m1 - m0)
    }
